import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { DEFAULT_AUTHOR, buildFileHeader, today } from '../header.js';
import { findRepoRoot, listBuiltinTemplates, loadCodegenConfig, resolveTemplate } from '../templates.js';

let tmpDir: string;

beforeEach(() => {
  tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'fw-cli-gen-tpl-'));
});

afterEach(() => {
  fs.rmSync(tmpDir, { recursive: true, force: true });
});

const baseOptions = {
  file: 'order.service.ts',
  description: '订单服务',
  moduleName: 'order',
  author: DEFAULT_AUTHOR,
  created: '2026-10-13',
};

describe('buildFileHeader', () => {
  it('ts 文件输出块注释且含全部必需标记（过 check:headers 门禁）', () => {
    const header = buildFileHeader(baseOptions);
    expect(header.startsWith('/*')).toBe(true);
    for (const marker of ['@file order.service.ts', '@description 订单服务', '@author donttemo', '@created 2026-10-13', '@module order', '@since', '@generated by @fw/cli']) {
      expect(header).toContain(marker);
    }
  });

  it('vue 文件输出 HTML 注释', () => {
    const header = buildFileHeader({ ...baseOptions, file: 'index.vue' });
    expect(header.startsWith('<!--')).toBe(true);
    expect(header.trimEnd().endsWith('-->')).toBe(true);
  });

  it('sql 文件输出行注释', () => {
    const header = buildFileHeader({ ...baseOptions, file: 'seed.sql' });
    expect(header.startsWith('-- @file seed.sql')).toBe(true);
  });
});

describe('today', () => {
  it('输出 YYYY-MM-DD（本地时区）', () => {
    expect(today(new Date('2026-01-05T23:30:00'))).toBe('2026-01-05');
    expect(today(new Date('2026-12-31T00:10:00'))).toBe('2026-12-31');
  });
});

describe('loadCodegenConfig', () => {
  it('配置文件缺失时返回空配置', () => {
    expect(loadCodegenConfig(tmpDir)).toEqual({});
  });

  it('配置文件损坏时抛出可定位错误', () => {
    fs.writeFileSync(path.join(tmpDir, 'codegen.config.json'), '{oops', 'utf8');
    expect(() => loadCodegenConfig(tmpDir)).toThrow('codegen.config.json 解析失败');
  });

  it('正常读取 vars 与 typeOverrides', () => {
    fs.writeFileSync(
      path.join(tmpDir, 'codegen.config.json'),
      JSON.stringify({ vars: { company: 'acme' }, typeOverrides: { Int: { control: 'switch' } } }),
      'utf8',
    );
    const config = loadCodegenConfig(tmpDir);
    expect(config.vars).toEqual({ company: 'acme' });
    expect(config.typeOverrides?.Int?.control).toBe('switch');
  });
});

describe('resolveTemplate', () => {
  it('项目级同名模板优先于内置模板', () => {
    const projectTpl = path.join(tmpDir, 'templates', 'codegen', 'backend');
    fs.mkdirSync(projectTpl, { recursive: true });
    fs.writeFileSync(path.join(projectTpl, 'entity.ts.tpl'), 'project', 'utf8');
    expect(resolveTemplate('backend/entity.ts.tpl', tmpDir)).toBe(path.join(projectTpl, 'entity.ts.tpl'));
  });

  it('无项目级模板时回退内置模板', () => {
    const builtin = resolveTemplate('backend/entity.ts.tpl', tmpDir);
    expect(builtin).toContain('templates');
    expect(fs.readFileSync(builtin, 'utf8')).toContain('BaseEntity');
  });

  it('两侧都缺失时报错', () => {
    expect(() => resolveTemplate('backend/nope.ts.tpl', tmpDir)).toThrow('模板缺失');
  });
});

describe('findRepoRoot 与 listBuiltinTemplates', () => {
  it('从 CLI 包位置向上找到仓库根', () => {
    expect(fs.existsSync(path.join(findRepoRoot(), 'pnpm-workspace.yaml'))).toBe(true);
  });

  it('列出内置模板（后端 6 + 前端 3 + seed 1）', () => {
    const templates = listBuiltinTemplates();
    expect(templates).toContain('backend/service.ts.tpl');
    expect(templates).toContain('frontend/index.vue.tpl');
    expect(templates).toContain('seed/permissions.ts.tpl');
    expect(templates).toHaveLength(10);
  });
});
